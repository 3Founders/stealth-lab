-- Dashboard-managed selling (founder decision 2026-11-02): the plans' numbers and the referral codes live here, edited in the
-- admin dashboard's Billing page (backend/app/api/admin_billing.py), instead of only in code. The site keeps its built-in copy
-- (routing_kell_frontend/lib/plans.ts) as the fallback while the server does not answer; keep the two in step.
--
--   billing_plan_rows          the price, period and included usage of each plan the server sells; a plan not active is not sold or shown
--   billing_referral_codes     the codes that unlock the one-person pilot: hand-issued (made in the dashboard) and personal
--                              (generated by the webhook for a buying account; referrer rewards are NOT built, the code only notes who owns it)
--   billing_orders.referral_code  the code an order was made with, so a later reward decision has a record to work from

CREATE TABLE IF NOT EXISTS billing_plan_rows (
    plan          TEXT PRIMARY KEY CHECK (plan IN ('starter', 'pro', 'plus', 'pilot')),
    price_paise   BIGINT NOT NULL CHECK (price_paise > 0 AND price_paise <= 500000 AND price_paise % 100 = 0),
    period_days   INTEGER NOT NULL CHECK (period_days BETWEEN 1 AND 365),
    included_usd  NUMERIC(14, 6) NOT NULL CHECK (included_usd > 0 AND included_usd <= 10000),
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by    TEXT,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The founders' numbers (docs/billing.md "Plans"), both as the seed and as what the server falls back to when this table
-- is missing (a server deployed before this migration): keep lib/plans.ts in step with these.
INSERT INTO billing_plan_rows (plan, price_paise, period_days, included_usd, updated_by) VALUES
    ('starter',  20000, 30, 1, 'seed'),
    ('pro',     120000, 30, 6, 'seed'),
    ('plus',    200000, 30, 12, 'seed'),
    ('pilot',    64900, 30, 4, 'seed')
ON CONFLICT (plan) DO NOTHING;

CREATE TABLE IF NOT EXISTS billing_referral_codes (
    code           TEXT PRIMARY KEY CHECK (code ~ '^[A-Z0-9]{4,32}$'),
    kind           TEXT NOT NULL DEFAULT 'issued' CHECK (kind IN ('issued', 'personal')),
    -- The buyer's user id for a personal code; NULL for an issued one. Deliberately no foreign key: migrations must not
    -- depend on the Supabase auth schema (tests/test_auth_hardening_offline.py), same rule as db/164.
    owner_user_id  UUID,
    note           TEXT CHECK (note IS NULL OR length(note) <= 200),
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_by     TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One personal code per buying account.
CREATE UNIQUE INDEX IF NOT EXISTS billing_referral_codes_one_personal_per_owner
    ON billing_referral_codes (owner_user_id) WHERE owner_user_id IS NOT NULL;

-- An order is a snapshot: it records the amount and period at the moment the order was made, so a later price edit never
-- rewrites it. This column only notes which referral code was used, for the audit trail.
ALTER TABLE billing_orders ADD COLUMN IF NOT EXISTS referral_code TEXT;
