JS_SRC = '''
/** Retry with backoff. */
export const retry = async (fn, attempts = 5) => {
  let delay = 100
  for (let i = 0; i < attempts; i++) {
    try { return await fn(i) }
    catch (err) {
      if (i === attempts - 1 || !err.retryable) throw err
      await sleep(delay * (1 + Math.random()))
      delay = Math.min(delay * 2, 10000)
    }
  }
}

res.send = function send(body) {
  var chunk = body
  if (typeof chunk === 'string') { this.set('Content-Type', 'text/html') }
  else if (Buffer.isBuffer(chunk)) { this.set('Content-Type', 'application/octet-stream') }
  else if (chunk !== null) { return this.json(chunk) }
  return this.end(chunk)
}

const api = { fetchAll: async function (ids) { const out = []; for (const id of ids) { if (!id) continue; out.push(await get(id)) } return out } }

function getName() { return this.name }
'''

GO_SRC = '''package q

// Run drains the queue until ctx is done.
func (s *S) Run(ctx context.Context, n int) error {
	defer s.mu.Unlock()
	for i := 0; i < n; i++ {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case job := <-s.jobs:
			if job == nil || job.done {
				continue
			}
			go s.handle(job)
		}
	}
	return nil
}

func (s *S) Name() string { return s.name }
'''


def test_js_finds_arrow_assignment_and_object_pair_functions_and_names_them():
    spans = {s.name: s for s in treesitter_features.extract_spans(JS_SRC, "javascript")}
    assert {"retry", "send", "fetchAll", "getName"} <= set(spans)
    assert spans["retry"].is_async and spans["retry"].has_loop and spans["retry"].has_docstring
    assert spans["retry"].cyclomatic >= 5 and spans["send"].cyclomatic >= 4
    assert spans["getName"].trivial_reason is not None, "a getter is plumbing"
    assert spans["send"].trivial_reason is None


def test_assignment_style_span_includes_its_whole_statement():
    send = {s.name: s for s in treesitter_features.extract_spans(JS_SRC, "javascript")}["send"]
    line = JS_SRC.splitlines()[send.line_start - 1]
    assert line.startswith("res.send = function send"), "the span starts at the assignment, not mid-expression"


def test_go_select_defer_and_goroutines_are_recognised():
    spans = {s.name: s for s in treesitter_features.extract_spans(GO_SRC, "go")}
    run = spans["Run"]
    assert run.has_loop and run.is_async and run.uses_context_manager and run.has_docstring
    assert run.cyclomatic >= 5 and run.max_nesting >= 2
    assert spans["Name"].trivial_reason is not None


