def test_content_gates_catch_generated_binary_minified_and_tiny_files():
    body = "value_number_one = compute_the_thing(argument)  # padding to clear the minimum size\n" * 30
    assert inventory.content_verdict("a.py", "# @generated by protoc\n" + body).reason == "generated_marker"
    assert inventory.content_verdict("a.py", "\x00" + body).reason == "binary"
    assert inventory.content_verdict("a.js", "var a=1;" * 200).reason == "minified_or_data_blob"
    assert inventory.content_verdict("a.py", "x = 1\n").reason in {"too_small", "too_few_lines"}
    assert inventory.content_verdict("a.py", "def f():\n    return 1\n" * 30).kept


