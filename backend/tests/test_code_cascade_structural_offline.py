# ------------------------------------------------------------------------------------------- S2 python features

def test_python_plumbing_is_named_and_real_logic_is_not():
    by_name = {s.name: s for s in python_features.extract_spans(PY_HARD)}
    assert by_name["parse_range"].trivial_reason is None
    # Box holds a getter, a setter, a delegate and a stub: however many branches its parts sum to, it teaches nothing
    assert by_name["Box"].trivial_reason == "plumbing_class"
    single = python_features.extract_spans("def get_x(o):\n    return o._x\n\ndef todo():\n    raise NotImplementedError\n")
    assert all(s.trivial_reason for s in single), "a getter and an abstract stub are plumbing"


def test_a_class_with_real_logic_in_one_method_is_not_plumbing():
    src = ("class A:\n    def get(self):\n        return self._x\n\n    def real(self, xs):\n        t = 0\n"
           "        for x in xs:\n            if x > 1 and x < 9:\n                t += x\n            elif x < 0:\n"
           "                t -= 1\n        return t\n")
    spans = python_features.extract_spans(src)
    assert spans[0].kind == "class" and spans[0].trivial_reason is None


def test_python_complexity_features_are_counted():
    f = {s.name: s for s in python_features.extract_spans(PY_HARD)}["parse_range"]
    assert f.cyclomatic >= 8 and f.max_nesting >= 3 and f.has_loop and f.has_docstring and f.uses_regex_or_bitops
    assert f.distinct_calls >= 6 and f.kind == "function" and f.line_start < f.line_end


def test_copy_pasted_python_with_renamed_variables_has_an_equal_fingerprint():
    a = "def f(xs):\n    t = 0\n    for x in xs:\n        if x > 1:\n            t += x\n    return t\n"
    b = "def g(items):\n    total = 0\n    for item in items:\n        if item > 9:\n            total += item\n    return total\n"
    assert python_features.extract_spans(a)[0].fingerprint == python_features.extract_spans(b)[0].fingerprint
    c = a.replace("if x > 1:", "while x > 1:")
    assert python_features.extract_spans(c)[0].fingerprint != python_features.extract_spans(a)[0].fingerprint


def test_python_syntax_errors_yield_no_spans_not_an_exception():
    assert python_features.extract_spans("def broken(:\n  pass") == []
    assert python_features.module_imports("def broken(:\n  pass") == set()


