def _span(**over):
    base = dict(name="f", kind="function", line_start=1, line_end=40, code_lines=30, cyclomatic=8, max_nesting=3,
                distinct_calls=8, branches=7, has_loop=True, has_recursion=False, is_async=False, is_generator=False,
                uses_context_manager=False, uses_regex_or_bitops=False, has_docstring=True, annotated_fraction=0.0,
                trivial_reason=None, fingerprint="x")
    base.update(over)
    return python_features.SpanFeatures(**base)


def test_plumbing_scores_exactly_zero_not_low():
    assert scoring.span_score(_span(trivial_reason="pure_delegate")) == 0.0


def test_more_decisions_nesting_and_variety_score_higher():
    base = scoring.span_score(_span())
    assert scoring.span_score(_span(cyclomatic=20)) > base
    assert scoring.span_score(_span(max_nesting=4)) > scoring.span_score(_span(max_nesting=1))
    assert scoring.span_score(_span(distinct_calls=15)) > scoring.span_score(_span(distinct_calls=2))
    assert scoring.span_score(_span(has_recursion=True)) > base


def test_the_size_window_rejects_snippets_too_small_or_too_large_for_a_small_model():
    assert scoring.size_window(4) == 0.0 and scoring.size_window(200) == 0.0
    assert scoring.size_window(30) == 1.0
    assert 0.0 < scoring.size_window(10) < 1.0 and 0.0 < scoring.size_window(120) < 1.0


def test_role_weights_put_source_before_examples_before_tests():
    assert scoring.ROLE_WEIGHT["source"] > scoring.ROLE_WEIGHT["example"] > scoring.ROLE_WEIGHT["test"]


