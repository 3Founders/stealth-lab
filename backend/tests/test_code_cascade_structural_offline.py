def test_the_cascade_reports_every_stage_and_keeps_only_non_trivial_source_first():
    repo = {
        "src/core.py": PY_HARD,
        "src/other.py": PY_HARD.replace("parse_range", "parse_span").replace("Box", "Crate"),
        "src/widget.js": JS_SRC,
        "tests/test_core.py": PY_HARD.replace("parse_range", "parse_test_range"),
        "vendor/big.py": PY_HARD,
        "README.md": "# hi\n" * 50,
        "src/data.rs": "fn x() {}\n" * 20,
    }
    result = run_structural_cascade(repo, max_spans=10, per_file=2)
    funnel = result.funnel.as_dict()
    assert funnel["files_in"] == 7 and funnel["s1_dropped"]["vendored_generated_or_boilerplate_path"] == 1
    assert funnel["s1_dropped"]["not_source_code"] == 1
    assert funnel["spans_plumbing"], "getters/delegates/stubs are counted, not silently lost"
    assert funnel["spans_duplicate"] >= 1, "the renamed copy in other.py is the same structure"
    kept = result.kept
    assert kept and all(k.ranked.score > 0 for k in kept)
    names = [k.ranked.features.name for k in kept]
    assert len(names) == len(set(k.ranked.features.fingerprint for k in kept)), "no two kept spans share a structure"
    assert {"retry", "send"} <= set(names) or {"send", "fetchAll"} <= set(names)
    source_first = [k.ranked.role for k in kept]
    assert source_first.index("source") < (source_first.index("test") if "test" in source_first else 99)
    for k in kept:
        assert k.text.splitlines()[0].strip() == inventory_first_line(repo[k.path], k)


def inventory_first_line(text: str, k) -> str:
    return text.splitlines()[k.line_start - 1].strip()


def test_per_file_cap_prevents_one_file_from_flooding_the_result():
    many = "\n".join(
        f"def f{i}(xs):\n    t = 0\n    for x in xs:\n        if x > {i}:\n            t += x * {i}\n        elif x < -{i}:\n            t -= 1\n    return t\n"
        .replace("x * ", "int(x) * ") + ("    # pad\n" * (i % 3)) for i in range(12))
    # distinct structures so the copy-paste dedupe does not thin them: vary the shape
    varied = []
    for i in range(12):
        body = "".join(f"    if xs[{j}] > {i}:\n        xs[{j}] += 1\n" for j in range(i % 5 + 2))
        varied.append(f"def g{i}(xs):\n    total = 0\n    for x in xs:\n        total += x\n{body}    return total\n")
    result = run_structural_cascade({"src/big.py": "\n".join(varied)}, max_spans=50, per_file=3)
    assert len(result.kept) <= 3
    assert result.funnel.files_with_kept_spans == 1
