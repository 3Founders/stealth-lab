"""Export the held-out task ids and repos from the experiment designs into a TRACKED file (BLOCKERS.md I15).

    python experiments/export_held_out_ids.py      # writes experiments/held_out_ids.json

`experiments/*/runs/design.json` is gitignored, so on a fresh clone, in CI or on a production worker the
ingestion gates had no held-out list and excluded nothing. This file carries only public identifiers (SWE-bench
instance ids and repository names) and the sha256 of each design they came from -- no task data.
Run it wherever the designs exist, after any change to a design, and commit the result.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESIGNS = ("experiments/swebench/runs/design.json", "experiments/swebench_rebench/runs/design.json")
SPLITS = ("test", "calibration")
OUT = ROOT / "experiments" / "held_out_ids.json"


def main() -> int:
    ids: set[str] = set()
    repos: set[str] = set()
    sources = []
    for rel in DESIGNS:
        path = ROOT / rel
        if not path.is_file():
            raise SystemExit(f"missing {rel}: export only where every design exists (a partial list would under-exclude)")
        raw = path.read_bytes()
        data = json.loads(raw.decode("utf-8"))
        counts = {}
        for split in SPLITS:
            values = [str(v) for v in data.get(split) or []]
            ids.update(values)
            counts[split] = len(values)
        scored = [str(v) for v in data.get("scored_repos") or []]
        repos.update(scored)
        sources.append({"design": rel, "sha256": hashlib.sha256(raw).hexdigest(), "counts": counts,
                        "scored_repos": len(scored)})
    OUT.write_text(json.dumps({
        "_doc": "Held-out ids and repos that ingestion must never admit (BLOCKERS.md I15). Generated by "
                "experiments/export_held_out_ids.py from the gitignored designs listed below; public ids only.",
        "splits": list(SPLITS),
        "sources": sources,
        "instance_ids": sorted(ids),
        "scored_repos": sorted(repos),
    }, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ids)} ids, {len(repos)} repos from {len(sources)} designs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
